create policy "profiles readable by authenticated users" on public.profiles for select to authenticated using (true);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id);

create policy "songs readable" on public.songs for select to authenticated using (true);

create policy "owners manage playlists" on public.playlists for all to authenticated
using (owner_id=auth.uid()) with check (owner_id=auth.uid());

create policy "playlist members can read tracks" on public.playlist_tracks for select to authenticated
using (exists(select 1 from public.playlists p where p.id=playlist_id and (p.owner_id=auth.uid() or p.is_public)));
create policy "playlist owners manage tracks" on public.playlist_tracks for all to authenticated
using (exists(select 1 from public.playlists p where p.id=playlist_id and p.owner_id=auth.uid()))
with check (exists(select 1 from public.playlists p where p.id=playlist_id and p.owner_id=auth.uid()));

create policy "users manage own likes" on public.likes for all to authenticated
using (user_id=auth.uid()) with check (user_id=auth.uid());
create policy "users manage own history" on public.listening_history for all to authenticated
using (user_id=auth.uid()) with check (user_id=auth.uid());

create policy "friend requests participants" on public.friendships for all to authenticated
using (requester_id=auth.uid() or addressee_id=auth.uid())
with check (requester_id=auth.uid());

create policy "blend members" on public.blends for select to authenticated
using (created_by=auth.uid() or exists(select 1 from public.blend_members bm where bm.blend_id=id and bm.user_id=auth.uid()));
create policy "blend creator" on public.blends for insert to authenticated with check (created_by=auth.uid());
create policy "blend membership" on public.blend_members for all to authenticated
using (user_id=auth.uid() or exists(select 1 from public.blends b where b.id=blend_id and b.created_by=auth.uid()))
with check (user_id=auth.uid());

create policy "jam members access" on public.jams for select to authenticated
using (host_id=auth.uid() or exists(select 1 from public.jam_members jm where jm.jam_id=id and jm.user_id=auth.uid()));
create policy "jam host creates" on public.jams for insert to authenticated with check (host_id=auth.uid());
create policy "jam host updates" on public.jams for update to authenticated using (host_id=auth.uid()) with check (host_id=auth.uid());

create policy "jam membership access" on public.jam_members for select to authenticated
using (user_id=auth.uid() or exists(select 1 from public.jams j where j.id=jam_id and j.host_id=auth.uid()));
create policy "users join jams" on public.jam_members for insert to authenticated with check (user_id=auth.uid());

create policy "jam state members" on public.jam_state for select to authenticated
using (exists(select 1 from public.jams j left join public.jam_members jm on jm.jam_id=j.id where j.id=jam_id and (j.host_id=auth.uid() or jm.user_id=auth.uid())));
create policy "jam state members update" on public.jam_state for all to authenticated
using (exists(select 1 from public.jams j left join public.jam_members jm on jm.jam_id=j.id where j.id=jam_id and (j.host_id=auth.uid() or jm.user_id=auth.uid())))
with check (exists(select 1 from public.jams j left join public.jam_members jm on jm.jam_id=j.id where j.id=jam_id and (j.host_id=auth.uid() or jm.user_id=auth.uid())));

